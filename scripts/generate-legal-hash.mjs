/**
 * Computes a SHA-256 over the legal documents' source and writes it to
 * `lib/core/legal/content-hash.generated.ts`.
 *
 * Runs automatically before every build (`prebuild` in package.json), so the
 * hash stored with a user's acceptance always matches the text that was
 * actually deployed. Doing it by hand would work exactly until the first time
 * someone forgot — and a stale hash is worse than none, because it looks like
 * proof while proving the wrong thing.
 *
 * The constants file is included on purpose: the pages interpolate retention
 * periods and notice days from it, so changing a number there changes the
 * document even though no prose moved.
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

const SOURCES = [
  'app/(marketplace)/terms/page.tsx',
  'app/(marketplace)/privacy/page.tsx',
  'app/(marketplace)/cookie/page.tsx',
  'lib/core/legal/processors.ts',
  'lib/core/guardians/age.ts',
  'lib/core/guardians/consent-document.ts',
];

const hash = createHash('sha256');
for (const rel of SOURCES) {
  // Normalise line endings: a Windows checkout must not produce a different
  // hash from the Linux build running on Vercel.
  hash.update(rel);
  hash.update(readFileSync(join(root, rel), 'utf8').replace(/\r\n/g, '\n'));
}
const digest = hash.digest('hex');

const out = join(root, 'lib/core/legal/content-hash.generated.ts');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `// GENERATED by scripts/generate-legal-hash.mjs — do not edit by hand.
// Regenerated before every build; commit the result so type-checking works
// without running the script first.
export const LEGAL_CONTENT_HASH = '${digest}';
`,
  'utf8'
);

console.log(`[legal] content hash: ${digest.slice(0, 16)}…`);
